"""Generate the C++ view of the lowering contract using only the stdlib."""
import hashlib
import json
from pathlib import Path

here = Path(__file__).resolve().parent
raw = (here.parent / "npu_compiler" / "v09_contract.json").read_bytes()
contract = json.loads(raw)
lines = ["// Generated by generate_contract.py; edit v09_contract.json instead.",
         "#pragma once", f'constexpr const char* kContractHash = "{hashlib.sha256(raw).hexdigest()}";',
         f'constexpr int64_t kMaxVlen = {contract["max_vlen"]};',
         f'constexpr const char* kSumUpdate = "{contract["reductions"]["sum_update"]}";']
for name, entries in [("STORAGE", contract["storage"]),
                      ("BINARY", contract["binary"]),
                      ("UNARY", contract["unary"]),
                      ("COMPOSITE", contract["composite"])]:
    rows = []
    for key, value in entries.items():
        if name == "STORAGE":
            rows.append(f'X("{key}", {value[0]}, {value[1]})')
        elif name == "UNARY":
            rows.append(f'X("{key}", {value})')
        elif name == "COMPOSITE":
            rows.append(f'X("{key}", {value[1]})')
        else:
            rows.append(f'X({key}Node, {value})')
    lines.append(f'#define NPU_{name}(X) ' + ' '.join(rows))
for name in ("vector_load", "generic_store"):
    lines.append(f'#define NPU_{name.upper()}(X) ' + ' '.join(
        f'X("{dtype}")' for dtype in contract[name]))
(here / "v09_contract.h").write_text('\n'.join(lines) + '\n')
